#!/usr/bin/env python3
"""Writes mix_tables.h for ext/mix_fx.c: log/exp tables, the 48/32 kHz
resampler phases and the delay filter coefficients.

    python3 tools/mix_tables.py ext/mix_tables.h
"""
import math, sys
from pathlib import Path
import numpy as np

OUT = Path(sys.argv[1])
FS = 48000

def kaiser_lowpass(n, cutoff, fs_proto, beta, offset):
    t = np.arange(n) - (n - 1) / 2 + offset
    h = 2 * cutoff / fs_proto * np.sinc(2 * cutoff / fs_proto * t)
    w = np.kaiser(n, beta)
    return h * w

lines = ["/* Generated by tools/mix_tables.py. */", "#ifndef MIX_TABLES_H", "#define MIX_TABLES_H", ""]
log = [round(65536 * math.log2(1 + i / 64)) for i in range(65)]
lines.append("/* log2(1 + i/64), Q16 */")
lines.append("static const u32 mix_log2_table[65] = {" + ", ".join(map(str, log)) + "};")
exp = [round((1 << 30) * 2 ** (i / 64)) for i in range(65)]
lines.append("/* 2^(i/64), Q30 */")
lines.append("static const u32 mix_exp2_table[65] = {" + ", ".join(map(str, exp)) + "};")

# Resampler. A 32 kHz sample j sits at 48 kHz time 1.5 j. Frames run in
# threes: frame 3m makes sample 2m at its own time, frame 3m+1 makes sample
# 2m+1, half a frame after it. Tap i reads the input i frames (or i 32 kHz
# samples) before the newest. Down: two phases of DOWN_TAPS at 48 kHz. Up:
# an output frame sits 0, -1/3 or +1/3 of a 32 kHz sample from the newest
# one, for frames 3m, 3m+1 and 3m+2.
CUT = 13500.0
DOWN_TAPS, UP_TAPS = 16, 12
def kernel(t, rate, taps, beta):
    h = (2 * CUT / rate) * np.sinc(2 * CUT / rate * t) * np.kaiser(taps, beta)
    return h / h.sum()
down = [kernel(np.arange(DOWN_TAPS) - (DOWN_TAPS - 1) / 2 + shift, FS, DOWN_TAPS, 7.0) for shift in (0.0, 0.5)]
up = [kernel(np.arange(UP_TAPS) - (UP_TAPS - 1) / 2 + shift, 32000, UP_TAPS, 6.0) for shift in (0.0, -1 / 3, 1 / 3)]
q = lambda h: "{" + ", ".join(str(round(v * 32768)) for v in h) + "}"
lines.append(f"#define MIX_DOWN_TAPS {DOWN_TAPS}")
lines.append(f"#define MIX_UP_TAPS {UP_TAPS}")
lines.append("/* 48 to 32 kHz, two phases; 32 to 48 kHz, three phases. Q15. */")
lines.append(f"static const s16 mix_down_fir[2][{DOWN_TAPS}] = {{" + ", ".join(q(h) for h in down) + "};")
lines.append(f"static const s16 mix_up_fir[3][{UP_TAPS}] = {{" + ", ".join(q(h) for h in up) + "};")

def onepole(f):
    return round(32768 * (1 - math.exp(-2 * math.pi * f / FS)))
LOW = [0, 20, 50, 100, 200, 400, 800]
HIGH = [1000, 2000, 3000, 5000, 8000, 12000, 0]
lines.append("/* Delay low cut (0: off) and high cut (0: off) in Hz, and one-pole coefficients, Q15. */")
lines.append("const u16 mix_low_cut_hz[MIX_FILTER_STEPS] = {" + ", ".join(map(str, LOW)) + "};")
lines.append("static const u16 mix_low_cut_coef[7] = {" + ", ".join(str(onepole(f) if f else 0) for f in LOW) + "};")
lines.append("const u16 mix_high_cut_hz[MIX_FILTER_STEPS] = {" + ", ".join(map(str, HIGH)) + "};")
lines.append("static const u16 mix_high_cut_coef[7] = {" + ", ".join(str(onepole(f) if f else 32767) for f in HIGH) + "};")
lines += ["", "#endif", ""]
OUT.write_text("\n".join(lines))
print(OUT)
